# Profundiozando en los sistemas de numeración

# Sistema Decimal

a = 10
print(f"a decimal: {a}")

# Sistema Binario
a = 0b1010
print(f"a binario: {a}")

# Sistema Octal
a = 0o12
print(f"a octal: {a}")

# Sistema Hexadecimal
a = 0xA
print(f"a hexadecimal: {a}")

# Base Decimal
a = int('23', 10)
print(f"a = base decimal: {a}")

# Base Binaria
a = int('10111', 2)
print(f"a = base binaria: {a}")

# Base Octal
a = int('27', 8)
print(f"a = base octal: {a}")

# Base Hexadecimal
a = int('17', 16)
print(f"a = base hexadecimal: {a}")

# Base 5 sus valores son de 0 a 4
a = int('344', 5)
print(f"a = base 5: {a}")